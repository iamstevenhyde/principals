// node tools/bundle.mjs : packs content/*.json into engine/content_bundle.js so the pages need no fetch().
// Rerun after any content edit. With no content yet it writes CONTENT = null and the pages use the stub fixture.
import { readFileSync, readdirSync, existsSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export function loadContent() {
  const dir = join(root, 'content');
  const bdir = join(dir, 'boards');
  const files = existsSync(bdir) ? readdirSync(bdir).filter(f => f.endsWith('.json')).sort() : [];
  if (!files.length) return null;
  const read = p => JSON.parse(readFileSync(p, 'utf8'));
  return {
    boards: files.map(f => read(join(bdir, f))),
    game: existsSync(join(dir, 'game.json')) ? read(join(dir, 'game.json')) : null,
  };
}
if (process.argv[1] && process.argv[1].endsWith('bundle.mjs')) {
  const c = loadContent();
  writeFileSync(join(root, 'engine', 'content_bundle.js'), '// Generated by tools/bundle.mjs. Do not edit; edit content/*.json and rerun.\nexport const CONTENT = ' + JSON.stringify(c, (k, v) => (['design_note', 'note', 'secret_scoring_note', 'rule'].includes(k) ? undefined : v)) + ';\n');
  console.log(c ? 'bundled ' + c.boards.length + ' boards' : 'no content yet; wrote CONTENT = null');
}
